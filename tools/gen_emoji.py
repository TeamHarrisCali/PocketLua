def fetch(cp):
    path = os.path.join(CACHE, "emoji_u%x.png" % cp)
    if not os.path.exists(path):
        try:
            with urllib.request.urlopen(URL % cp, timeout=20) as r:
                data = r.read()
        except Exception as e:  # noqa: BLE001 - a missing picture is skipped
            print("skipped U+%X: %s" % (cp, e), file=sys.stderr)
            return None
        with open(path, "wb") as f:
            f.write(data)
    return path


def rgb565(r, g, b):
    v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return 0x0000 if v == CLEAR else v


def main():
    os.makedirs(CACHE, exist_ok=True)
    seen, cps, rows = set(), [], []
    for cp in EMOJI:
        if cp in seen:
            continue
        seen.add(cp)
        path = fetch(cp)
        if not path:
            continue
        img = Image.open(path).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
        px = []
        for y in range(SIZE):
            for x in range(SIZE):
                r, g, b, a = img.getpixel((x, y))
                px.append(CLEAR if a < 110 else rgb565(r, g, b))
        cps.append(cp)
        rows.append(px)
    with open(OUT, "w") as f:
        f.write("// Generated by tools/gen_emoji.py: do not edit. The pictures are Noto Emoji\n"
                "// (https://github.com/googlefonts/noto-emoji), Apache License 2.0, scaled to\n"
                "// %dx%d. In picker order, most used first.\n#pragma once\n#include <stdint.h>\n\n" % (SIZE, SIZE))
        f.write("static const int EMOJI_SIZE = %d, EMOJI_COUNT = %d;\n" % (SIZE, len(cps)))
        f.write("static const uint16_t EMOJI_CLEAR = 0x%04x;\n" % CLEAR)
        f.write("static const uint32_t EMOJI_CP[] = {\n")
        for i in range(0, len(cps), 10):
            f.write("    " + ", ".join("0x%X" % c for c in cps[i:i + 10]) + ",\n")
        f.write("};\nstatic const uint16_t EMOJI_PX[][%d] = {\n" % (SIZE * SIZE))
        for cp, px in zip(cps, rows):
            f.write("    {" + ",".join("0x%04x" % v for v in px) + "},  // U+%X\n" % cp)
        f.write("};\n")
    print("%s: %d emoji, %d bytes of pictures" % (OUT, len(cps), len(cps) * SIZE * SIZE * 2))


if __name__ == "__main__":
    main()
