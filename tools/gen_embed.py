"""Embed userland/**/*.lua into the firmware as src/embedded_files.gen.cpp.

Each file is embedded as source (for the editor and debugging) and as
stripped bytecode, which loads with about half the RAM of compiling the
source on the device. The bytecode comes from tools/luac32.c, built here
from lib/lua/src with the device's 32-bit number types.

Runs before every build. The file is only rewritten when its content changes.
"""
Import("env")  # noqa: F821 (SCons)
import glob, os, subprocess, sys, tempfile

proj = env["PROJECT_DIR"]  # noqa: F821
root = os.path.join(proj, "userland")
out = os.path.join(proj, "src", "embedded_files.gen.cpp")

files = []
for dirpath, _, names in os.walk(root):
    for name in names:
        if name.endswith(".lua"):
            full = os.path.join(dirpath, name)
            files.append((os.path.relpath(full, root).replace(os.sep, "/"), full))
files.sort()

# the host compiler, rebuilt when its sources change
luac = os.path.join(proj, ".pio", "luac32")
srcs = [os.path.join(proj, "tools", "luac32.c")] + glob.glob(os.path.join(proj, "lib", "lua", "src", "*.c"))
if not os.path.exists(luac) or max(os.path.getmtime(f) for f in srcs) > os.path.getmtime(luac):
    os.makedirs(os.path.dirname(luac), exist_ok=True)
    subprocess.check_call(["cc", "-O2", "-o", luac, "-I" + os.path.join(proj, "lib", "lua", "src")] + srcs + ["-lm"])


def bytecode(path):
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, "out.luac")
        r = subprocess.run([luac, path, out], capture_output=True, text=True)
        if r.returncode != 0:  # the device compiles the source and reports the error
            sys.stderr.write("gen_embed: no bytecode for %s: %s" % (path, r.stderr))
            return b""
        with open(out, "rb") as f:
            return f.read()

lines = ["// generated by tools/gen_embed.py - do not edit", '#include "embedded.h"', ""]
codes = []
for i, (_, full) in enumerate(files):
    with open(full, "rb") as f:
        data = f.read()
    lines.append("static const unsigned char f%d[] = {%s};" % (i, ",".join(str(b) for b in data) or "0"))
    code = bytecode(full)
    codes.append(len(code))
    lines.append("static const unsigned char c%d[] = {%s};" % (i, ",".join(str(b) for b in code) or "0"))
lines.append("const EmbFile EMBEDDED[] = {")
for i, (rel, full) in enumerate(files):
    lines.append('  {"%s", f%d, %d, %s, %d},' % (rel, i, os.path.getsize(full), "c%d" % i if codes[i] else "nullptr", codes[i]))
lines.append("};")
lines.append("const size_t EMBEDDED_COUNT = %d;" % len(files))
text = "\n".join(lines) + "\n"

old = None
if os.path.exists(out):
    with open(out) as f:
        old = f.read()
if old != text:
    with open(out, "w") as f:
        f.write(text)
