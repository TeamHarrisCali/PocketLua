-- Regenerates userland/lib/icons.lua from tools/icons_src.lua.
-- The source draws each icon with gfx calls; this records those calls once and
-- stores them as compact strings, which take a fraction of the RAM that the
-- compiled functions would on the device.  Run: lua5.4 tools/gen_icons.lua
local FG, BG = 1000001, 1000002
local ops
local function rec(code) return function(...) ops[#ops + 1] = { code, ... } end end
gfx = { line = rec("L"), fill = rec("F"), rect = rec("R"), rrect = rec("r"), rfill = rec("Q"),
  circle = rec("C"), disc = rec("D"), tri = rec("T"), arc = rec("A") }
local icons = dofile("tools/icons_src.lua")
local X, Y = 100, 100
local names = {}
for name in pairs(icons) do names[#names + 1] = name end
table.sort(names)
local out = { "-- Generated by tools/gen_icons.lua from tools/icons_src.lua; edit the source and regenerate.",
  "-- Each icon is a list of drawing ops relative to the icon centre: an op letter",
  "-- (L line, F fill, R rect, r rrect, Q rfill, C circle, D disc, T tri, A arc),",
  "-- numbers, then f or b for the foreground or tile colour.",
  "local data = {" }
for _, name in ipairs(names) do
  ops = {}
  icons[name](X, Y, FG, BG)
  local parts = {}
  for _, op in ipairs(ops) do
    local code, args = op[1], {}
    local n = #op - 1
    for i = 2, n do
      local v = op[i]
      -- x arguments are even positions after the code for points; offset all coords by
      -- the centre: the renderer adds x to odd and y to even coordinate slots per op.
      args[#args + 1] = v
    end
    -- coordinate slots per op (1-based among args): which are x and which are y
    local XY = { L = "xyxy", F = "xy..", R = "xy..", r = "xy...", Q = "xy...", C = "xy.", D = "xy.", T = "xyxyxy", A = "xy...." }
    local map = XY[code]
    for i = 1, #args do
      local k = map:sub(i, i)
      if k == "x" then args[i] = math.floor(args[i] - X + 0.5)
      elseif k == "y" then args[i] = math.floor(args[i] - Y + 0.5)
      elseif type(args[i]) == "number" and args[i] % 1 ~= 0 then args[i] = math.floor(args[i] + 0.5) end
    end
    local c = op[#op]
    parts[#parts + 1] = code .. table.concat(args, ",") .. (c == BG and "b" or "f")
  end
  out[#out + 1] = string.format("  %s = %q,", name, table.concat(parts, " "))
end
out[#out + 1] = "}"
out[#out + 1] = [==[

local icons = {}
local parsed = {}  -- name -> list of { code, n1, n2, ..., is_tile_colour }, built on first use

local function parse(name)
  local list = {}
  for code, nums, c in data[name]:gmatch("(%a)([%-%d,]*)([fb])") do
    local op = { code }
    for v in nums:gmatch("%-?%d+") do op[#op + 1] = tonumber(v) end
    op[#op + 1] = c == "b"
    list[#list + 1] = op
  end
  parsed[name] = list
  return list
end

-- Draws icon `name` centred at (x, y). Direct calls per op: no garbage per frame.
function icons.draw(name, x, y, fg, bg)
  if not data[name] then name = "app" end
  local list = parsed[name] or parse(name)
  for i = 1, #list do
    local o = list[i]
    local c, k = o[#o] and bg or fg, o[1]
    if k == "L" then gfx.line(x + o[2], y + o[3], x + o[4], y + o[5], c)
    elseif k == "F" then gfx.fill(x + o[2], y + o[3], o[4], o[5], c)
    elseif k == "R" then gfx.rect(x + o[2], y + o[3], o[4], o[5], c)
    elseif k == "r" then gfx.rrect(x + o[2], y + o[3], o[4], o[5], o[6], c)
    elseif k == "Q" then gfx.rfill(x + o[2], y + o[3], o[4], o[5], o[6], c)
    elseif k == "C" then gfx.circle(x + o[2], y + o[3], o[4], c)
    elseif k == "D" then gfx.disc(x + o[2], y + o[3], o[4], c)
    elseif k == "T" then gfx.tri(x + o[2], y + o[3], x + o[4], y + o[5], x + o[6], y + o[7], c)
    elseif k == "A" then gfx.arc(x + o[2], y + o[3], o[4], o[5], o[6], o[7], c) end
  end
end

return icons
]==]
local f = assert(io.open("userland/lib/icons.lua", "w"))
f:write(table.concat(out, "\n"))
f:close()
print("wrote userland/lib/icons.lua with " .. #names .. " icons")
