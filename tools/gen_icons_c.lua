-- Writes src/icons.gen.h from tools/icons_src.lua: each icon as a list of
-- drawing ops relative to its centre, for the native UI (flash, no RAM).
-- Run: lua5.4 tools/gen_icons_c.lua
local FG, BG = 1000001, 1000002
local ops
local function rec(code) return function(...) ops[#ops + 1] = { code, ... } end end
gfx = { line = rec("L"), fill = rec("F"), rect = rec("R"), rrect = rec("r"), rfill = rec("Q"),
  circle = rec("C"), disc = rec("D"), tri = rec("T"), arc = rec("A") }
local icons = dofile("tools/icons_src.lua")
local XY = { L = "xyxy", F = "xy..", R = "xy..", r = "xy...", Q = "xy...", C = "xy.", D = "xy.", T = "xyxyxy", A = "xy...." }
local X, Y = 100, 100
local names = {}
for name in pairs(icons) do names[#names + 1] = name end
table.sort(names)
local out = { "// Generated by tools/gen_icons_c.lua from tools/icons_src.lua - do not edit.",
  "#pragma once", "#include <stdint.h>", "",
  "struct IconOp { char code; uint8_t bg; int16_t a[6]; };",
  "struct IconDef { const char *name; const IconOp *ops; uint8_t count; };", "" }
local defs = {}
for i, name in ipairs(names) do
  ops = {}
  icons[name](X, Y, FG, BG)
  local rows = {}
  for _, op in ipairs(ops) do
    local code, map, a = op[1], XY[op[1]], {}
    for k = 2, #op - 1 do
      local v, m = op[k], map:sub(k - 1, k - 1)
      if m == "x" then v = v - X elseif m == "y" then v = v - Y end
      a[#a + 1] = math.floor(v + 0.5)
    end
    while #a < 6 do a[#a + 1] = 0 end
    rows[#rows + 1] = string.format("{'%s', %d, {%s}}", code, op[#op] == BG and 1 or 0, table.concat(a, ", "))
  end
  out[#out + 1] = string.format("static const IconOp ICON_%d[] = {%s};", i, table.concat(rows, ", "))
  defs[#defs + 1] = string.format('  {"%s", ICON_%d, %d},', name, i, #rows)
end
out[#out + 1] = ""
out[#out + 1] = "static const IconDef ICONS[] = {"
for _, d in ipairs(defs) do out[#out + 1] = d end
out[#out + 1] = "};"
out[#out + 1] = string.format("static const int ICON_COUNT = %d;", #names)
local f = assert(io.open("src/icons.gen.h", "w"))
f:write(table.concat(out, "\n") .. "\n")
f:close()
print("wrote src/icons.gen.h with " .. #names .. " icons")
