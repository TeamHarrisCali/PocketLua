#!/usr/bin/env python3
"""Make BearSSL trust anchors (C) from root certificates, standard library only.

  gen_trust_anchors.py OUT.h NAME cert1.pem [cert2.pem ...]

Writes the subject name and public key of each certificate, and a function
NAME(br_x509_trust_anchor *out) that fills them in (EC P-256/P-384 and RSA
keys). Used for src/discord_ta.h:

  gen_trust_anchors.py src/discord_ta.h discordTrustAnchors \\
      /etc/ssl/certs/GTS_Root_R1.pem /etc/ssl/certs/GTS_Root_R4.pem
"""
import base64, sys

OID_RSA = "1.2.840.113549.1.1.1"
OID_EC = "1.2.840.10045.2.1"
CURVES = {"1.2.840.10045.3.1.7": "BR_EC_secp256r1", "1.3.132.0.34": "BR_EC_secp384r1"}


def tlv(b, i):
    """(tag, value start, end) of the DER element at i."""
    tag, n = b[i], b[i + 1]
    i += 2
    if n & 0x80:
        k = n & 0x7F
        n = int.from_bytes(b[i:i + k], "big")
        i += k
    return tag, i, i + n


def children(b, start, end):
    out, i = [], start
    while i < end:
        tag, s, e = tlv(b, i)
        out.append((tag, i, s, e))
        i = e
    return out


def oid(v):
    first = v[0]
    parts, n = [first // 40, first % 40], 0
    for c in v[1:]:
        n = n << 7 | (c & 0x7F)
        if not c & 0x80:
            parts.append(n)
            n = 0
    return ".".join(map(str, parts))


def parse(pem):
    der = base64.b64decode("".join(l for l in pem.splitlines() if l and not l.startswith("-----")))
    _, s, e = tlv(der, 0)
    tbs = children(der, s, e)[0]
    f = children(der, tbs[2], tbs[3])
    if f[0][0] == 0xA0:  # explicit version
        f = f[1:]
    subject = der[f[4][1]:f[4][3]]
    spki = f[5]
    alg, bits = children(der, spki[2], spki[3])
    algf = children(der, alg[2], alg[3])
    key_oid = oid(der[algf[0][2]:algf[0][3]])
    key = der[bits[2] + 1:bits[3]]  # skip the "unused bits" byte
    if key_oid == OID_EC:
        return subject, ("ec", CURVES[oid(der[algf[1][2]:algf[1][3]])], key)
    if key_oid == OID_RSA:
        n, e = children(key, *tlv(key, 0)[1:])
        mod = key[n[2]:n[3]].lstrip(b"\0")
        return subject, ("rsa", mod, key[e[2]:e[3]])
    raise SystemExit("unsupported key type " + key_oid)


def arr(name, data):
    rows = [", ".join("0x%02x" % x for x in data[i:i + 16]) for i in range(0, len(data), 16)]
    return "static const unsigned char %s[] = {\n  %s\n};" % (name, ",\n  ".join(rows))


def main():
    out, fn, certs = sys.argv[1], sys.argv[2], sys.argv[3:]
    if not certs:
        sys.exit(__doc__)
    lines = ["// Generated by tools/gen_trust_anchors.py from: " + ", ".join(certs), "#pragma once",
             '#include "bearssl.h"', ""]
    fill = []
    for i, path in enumerate(certs):
        subject, key = parse(open(path).read())
        lines.append(arr("TA%d_DN" % i, subject))
        fill.append("  out[%d].dn.data = (unsigned char *)TA%d_DN;\n  out[%d].dn.len = sizeof TA%d_DN;\n"
                    "  out[%d].flags = BR_X509_TA_CA;" % (i, i, i, i, i))
        if key[0] == "ec":
            lines.append(arr("TA%d_Q" % i, key[2]))
            fill.append("  out[%d].pkey.key_type = BR_KEYTYPE_EC;\n  out[%d].pkey.key.ec.curve = %s;\n"
                        "  out[%d].pkey.key.ec.q = (unsigned char *)TA%d_Q;\n  out[%d].pkey.key.ec.qlen = sizeof TA%d_Q;"
                        % (i, i, key[1], i, i, i, i))
        else:
            lines.append(arr("TA%d_N" % i, key[1]))
            lines.append(arr("TA%d_E" % i, key[2]))
            fill.append("  out[%d].pkey.key_type = BR_KEYTYPE_RSA;\n  out[%d].pkey.key.rsa.n = (unsigned char *)TA%d_N;\n"
                        "  out[%d].pkey.key.rsa.nlen = sizeof TA%d_N;\n  out[%d].pkey.key.rsa.e = (unsigned char *)TA%d_E;\n"
                        "  out[%d].pkey.key.rsa.elen = sizeof TA%d_E;" % (i, i, i, i, i, i, i, i, i))
        lines.append("")
    lines.append("static const size_t %s_COUNT = %d;" % (fn.upper(), len(certs)))
    lines.append("static void %s(br_x509_trust_anchor *out) {\n%s\n}" % (fn, "\n".join(fill)))
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
